#!/usr/bin/env python3
"""
Generate stand-in DriverKit implementation files for the XNU build.

Apple's `iig` tool (closed source) normally generates <Class>.iig.cpp: the RPC
marshalling for DriverKit (user-space driver) interfaces. Without it the kernel
fails to link. This script reads the linker's undefined-symbol list and emits:
  * metaclass definitions for classes that only exist as DriverKit interfaces
  * a stub returning kIOReturnUnsupported for every remaining generated method
The kernel then links and runs; user-space DriverKit drivers are non-functional.

usage: gen-iig-stubs.py <undefined.txt> <outdir> [kernel-symbols (nm -n output)]
"""
import re, sys, os

undefined = [l.strip() for l in open(sys.argv[1]) if l.strip()]
outdir = sys.argv[2]

# class -> superclass, for classes whose OSMetaClass the generated code owns
META = {
    'IODispatchSource': ('OSObject', True),
    'IOEventLink': ('OSObject', False),
    'IOWorkGroup': ('OSObject', False),
    'IODispatchQueue': ('OSObject', False),
    'OSAction': ('OSObject', False),
    'IODataQueueDispatchSource': ('IODispatchSource', False),
    'IOInterruptDispatchSource': ('IODispatchSource', False),
    'IOServiceNotificationDispatchSource': ('IODispatchSource', False),
    'IOServiceStateNotificationDispatchSource': ('IODispatchSource', False),
    # Declared by the DriverKit headers (a newer DriverKit than the rest of this XNU:
    # IOUserClient.h), but implemented nowhere: the metaclass below stands in for iig's.
    'OSAction_IOUserClient_KernelCompletion': ('OSAction', False),
    # Listed in config/Private.arm64.exports but defined in no source of this XNU
    # (nor in the DriverKit headers the iig shim uses): an exports-only class.
    # Nothing references it; the metaclass and the stubs below exist so that
    # config/check_all_exports, which requires every listed name, passes.
    'IOUnifiedAddressTranslator': ('OSObject', False),
}

# Classes of META that the headers do declare but that need a key function defined here
# so that their vtable (also on the exports lists) is emitted in this TU.
VTABLE_KEY = {
    'OSAction_IOUserClient_KernelCompletion':
        'kern_return_t\nOSAction_IOUserClient_KernelCompletion::Dispatch(const IORPC rpc)\n{\n    return kIOReturnUnsupported;\n}',
}

meta_needed, funcs, c_syms = [], [], []
for sym in undefined:
    m = re.match(r'__ZN(\d+)', sym)
    if not m:
        # a plain C symbol (SoC tables, pmap helpers): a data or function stub below
        if re.match(r'^_[A-Za-z]', sym):
            c_syms.append(sym)
        continue
    n = int(m.group(1)); cls = sym[len(m.group(0)):len(m.group(0)) + n]
    if sym == '__ZN%d%s9metaClassE' % (n, cls) or \
       sym == '__ZN%d%s10gMetaClassE' % (n, cls) or \
       sym == '__ZN%d%s10superClassE' % (n, cls):
        meta_needed.append(cls)
    else:
        funcs.append(sym)
vt = [s for s in undefined if s.startswith('__ZTV')]

out = ['/* Generated by gen-iig-stubs.py: stand-in for iig output. Do not edit. */',
       '#include <IOKit/IOLib.h>', '#include <IOKit/IOReturn.h>', '#include <IOKit/IOService.h>',
       '#include <IOKit/IOUserClient.h>', '#include <IOKit/IOUserServer.h>',
       '#include <DriverKit/IODispatchSource.h>', '#include <DriverKit/IODispatchQueue.h>',
       '#include <DriverKit/IOEventLink.h>', '#include <DriverKit/IOWorkGroup.h>', '#include <DriverKit/OSAction.h>',
       '#include <DriverKit/IODataQueueDispatchSource.h>', '#include <DriverKit/IOInterruptDispatchSource.h>',
       '#include <DriverKit/IOServiceNotificationDispatchSource.h>',
       '#include <DriverKit/IOServiceStateNotificationDispatchSource.h>',
       '#include <DriverKit/IOUserClient.h>', '',
       '/* exports-only classes (see META): no header declares them, and the metaclass',
       '   and the metaclass macros need a complete type, so a minimal one is declared',
       '   here. The methods below are unreferenced stubs; the hierarchy is nominal. */',
       'class IOUnifiedAddressTranslator : public OSObject',
       '{',
       '    OSDeclareDefaultStructors(IOUnifiedAddressTranslator);',
       '};', '']
want = set(meta_needed)
if any(META.get(c, ('', 0))[0] == 'IODispatchSource' for c in want) or vt:
    want.add('IODispatchSource')
for cls, (sup, abstract) in META.items():
    if cls in want:
        macro = 'OSDefineMetaClassAndAbstractStructors' if abstract else 'OSDefineMetaClassAndStructors'
        out.append('%s(%s, %s);' % (macro, cls, sup))
        if cls in VTABLE_KEY:
            out.append(VTABLE_KEY[cls])
out.append('')
# Kernel-implemented methods: the real generated wrapper marshals the call into
# an RPC and dispatches it back to Class::Method_Impl(). For objects that live
# in the kernel that round trip is equivalent to calling _Impl directly, and
# the kernel itself relies on it (e.g. IOService::StateNotificationItemCreate).
# The wrapper only has one extra trailing argument (the "supermethod"), so a
# tail branch is argument-compatible on arm64.
SUPER = 'PFiP15OSMetaClassBase5IORPCE'
defined = set()
present = set()
if len(sys.argv) > 3:
    for line in open(sys.argv[3]):
        parts = line.split()
        if len(parts) == 3 and parts[1] in 'tTsS':  # kernel text lives in __TEXT_EXEC, which nm reports as 'S'
            defined.add(parts[2])
    for line in open(sys.argv[3]):
        parts = line.split()
        if len(parts) == 3 and parts[1] != 'U':
            present.add(parts[2])

def impl_name(sym):
    m = re.match(r'__ZN(\d+)', sym)
    if not m or not sym.endswith(SUPER):
        return None
    pos = len(m.group(0)) + int(m.group(1))
    m2 = re.match(r'(\d+)', sym[pos:])
    if not m2:
        return None
    mlen = int(m2.group(1)); mstart = pos + len(m2.group(1))
    method = sym[mstart:mstart + mlen]
    rest = sym[mstart + mlen:]
    if not rest.startswith('E'):
        return None
    params = rest[1:-len(SUPER)] or 'v'
    return '%s%d%s_ImplE%s' % (sym[:pos], mlen + 5, method, params)

direct, unsupported = [], []
for sym in sorted(set(funcs)):
    impl = impl_name(sym)
    if impl and impl in defined:
        direct.append((sym, impl))
    else:
        unsupported.append(sym)

out.append('/* wrappers forwarded straight to their kernel implementation */')
for sym, impl in direct:
    out.append('__asm__(".text\\n.globl %s\\n.p2align 2\\n%s:\\n\\tb %s\\n");' % (sym, sym, impl))
out.append('')
out.append('/* everything else (RPC dispatch, user-space-only methods) is not available */')
out.append('extern "C" {')
for i, sym in enumerate(unsupported):
    # sym carries the Mach-O leading underscore already
    out.append('kern_return_t __iig_stub_%d(void) __asm__("%s");' % (i, sym))
    out.append('kern_return_t __iig_stub_%d(void) { return kIOReturnUnsupported; }' % i)
out.append('}')
# Plain C names from the exports lists that the binary does not define (unreferenced
# SoC tables and pmap helpers, e.g. the DART descriptors): defined here, only so that
# check_all_exports finds them. Only emitted with the kernel-symbols argument, which is
# what tells the names the binary already has apart. The suffix decides data vs function
# (pmap_*configuration and friends are functions taking no arguments, declared in
# osfmk/vm/pmap.h but compiled only for x86); neither is ever called (the link itself
# has no reference to any of them).
_DATA_SUFFIXES = ('_vo_tte', '_vo_tt_index', '_max_translation_levels')
# A few of the names above are declared by headers this TU includes (osfmk/vm/pmap.h);
# the stub has to carry the declared signature then. The rest are undeclared anywhere.
_C_SIGNATURES = {
    '_pmap_cs_configuration': 'int pmap_cs_configuration(void) { return 0; }',
    '_pmap_has_iofilter_protected_write': 'bool pmap_has_iofilter_protected_write(void) { return false; }',
}
out.append('/* plain C exports the binary does not define (unreferenced SoC/pmap names) */')
out.append('extern "C" {')
n_c = 0
for sym in sorted(set(c_syms)):
    if len(sys.argv) <= 3 or sym in present:
        continue
    name = sym[1:]  # the source name: the toolchain adds the Mach-O underscore itself
    if sym in _C_SIGNATURES:
        out.append(_C_SIGNATURES[sym])
    elif sym.endswith(_DATA_SUFFIXES):
        out.append('unsigned long long %s = 0;' % name)
    else:
        out.append('unsigned long long %s(void) { return 0; }' % name)
    n_c += 1
out.append('}')
os.makedirs(outdir, exist_ok=True)
open(os.path.join(outdir, 'OSObject.iig.cpp'), 'w').write('\n'.join(out) + '\n')
print('metaclasses:', len(want), 'forwarded to _Impl:', len(direct), 'unsupported stubs:', len(unsupported), 'plain C stubs:', n_c)
